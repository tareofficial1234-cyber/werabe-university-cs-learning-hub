/* =========================================================
   DATABASE MIGRATION
========================================================= */

async function migrateUsers() {
  try {
    if (isPostgres) {
      const result = await db
        .prepare(
          `
        SELECT column_name
        FROM information_schema.columns
        WHERE table_name='users'
          AND column_name='isactive'
      `,
        )
        .all();

      const hasColumn = result.length > 0;

      if (!hasColumn) {
        await db.exec(`
          ALTER TABLE users
          ADD COLUMN IF NOT EXISTS isActive INTEGER DEFAULT 1
        `);
      }
    } else {
      const columns = await db.prepare("PRAGMA table_info(users)").all();

      const names = columns.map((x) => x.name);

      if (!names.includes("isActive")) {
        await db.exec(
          "ALTER TABLE users ADD COLUMN isActive INTEGER DEFAULT 1",
        );
      }
    }
  } catch (error) {
    console.error("Migration warning:", error.message);
  }
}

