app.post("/api/auth/register", async (req, res) => {
  try {
    const { name, email, password, year, section } = req.body;

    if (!name || !email || !password || password.length < 8) {
      return res.status(400).json({
        error:
          "Name, email and a password of at least 8 characters are required",
      });
    }

    const cleanName = name.trim();
    const cleanEmail = email.toLowerCase().trim();

    const result = await db
      .prepare(
        `
          INSERT INTO users
          (name,email,password_hash,role,year,section)
          VALUES(?,?,?,?,?,?)
        `,
      )
      .run(
        cleanName,
        cleanEmail,
        bcrypt.hashSync(password, 12),
        "student",
        year || "",
        section || "",
      );

    req.session.user = {
      id: result.lastInsertRowid,
      name: cleanName,
      email: cleanEmail,
      role: "student",
    };

    res.json({
      user: req.session.user,
    });
  } catch (error) {
    console.error(error);

    res.status(400).json({
      error: "Email is already registered",
    });
  }
});

app.post("/api/auth/login", async (req, res) => {
  try {
    const email = (req.body.email || "").toLowerCase().trim();

    const u = await db.prepare("SELECT * FROM users WHERE email=?").get(email);

    if (
      !u ||
      !u.isActive ||
      !bcrypt.compareSync(req.body.password || "", u.password_hash)
    ) {
      return res.status(401).json({
        error: "Invalid email or password",
      });
    }

    req.session.user = {
      id: u.id,
      name: u.name,
      email: u.email,
      role: u.role,
      year: u.year,
      section: u.section,
    };

    res.json({
      user: req.session.user,
    });
  } catch (error) {
    console.error(error);

    res.status(500).json({
      error: "Login failed",
    });
  }
});

app.post("/api/auth/logout", (req, res) => {
  req.session.destroy(() => res.json({ ok: true }));
});

app.post("/api/auth/change-password", auth, async (req, res) => {
  try {
    const { currentPassword, newPassword } = req.body;

    if (!currentPassword || !newPassword || newPassword.length < 8) {
      return res.status(400).json({
        error:
          "Current password and a new password of at least 8 characters are required",
      });
    }

    const row = await db
      .prepare("SELECT password_hash FROM users WHERE id=?")
      .get(user(req).id);

    if (!row || !bcrypt.compareSync(currentPassword, row.password_hash)) {
      return res.status(400).json({
        error: "Current password is incorrect",
      });
    }

    await db
      .prepare("UPDATE users SET password_hash=? WHERE id=?")
      .run(bcrypt.hashSync(newPassword, 12), user(req).id);

    res.json({ ok: true });
  } catch (error) {
    console.error(error);

    res.status(500).json({
      error: "Could not change password",
    });
  }
});

